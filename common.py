@dataclasses.dataclass(frozen=True, repr=True, eq=True, order=True)
class Conf(dict):
    dynamical_model: str = ''
    mlp_layer_width: int = 10  # change back to 5
    mlp_depth: int = 5  # change back to 1
    init_scale: float = 0.1
    activation_fn_name: str = "relu"
    optimiser: str = "adam"
    max_lrate: float = 0.1  # absolute maximum learning rate (max in first schedule or in all schedules without decay)
    lrate_span: float = 1e1  # ratio between max and min learning rates in a given schedule
    lrate_decay: float = 0.8  # if < 1, the learning rate decays between schedules
    warmup_fct: float = 0.2  # fraction of schedule epochs to be used for warmup
    opt_steps: int = 10  # Number of steps in the first schedule (they multiply each time in length by opt_mult)
    opt_mult: int = 2  # Multiplier for the number of steps in each schedule
    use_early_stop: bool = True
    reg_exp: float = 1.0
    reg_strength: float = 10.0

    def __str__(self):
        """
        Return string representation of the configuration.

        Note: enables printing of Conf objects in fire
        """
        return super().__str__()


@dataclasses.dataclass
class EarlyStoppingParams(dict):
    use_early_stopping: bool = True
    patience: int = 9
    min_improvement: float = 0


def _init_glorot(scale, shape, key):
    init = jnn.initializers.variance_scaling(scale, "fan_avg", "uniform")
    return init(key, shape)


def set_weight_bias(mlp, scale, key):
    """
    Set the bias to zero, and use a glorot_uniform with provided scale for the 
    weights
    """
    is_linear = lambda x: isinstance(x, eqx.nn.Linear)
    _get_bias = lambda m: [x.bias
                           for x in jax.tree_util.tree_leaves(m, is_leaf=is_linear)
                           if is_linear(x)]
    _get_weight = lambda m: [x.weight
                             for x in jax.tree_util.tree_leaves(m, is_leaf=is_linear)
                             if is_linear(x)]

    weight_old = _get_weight(mlp)
    bias_old = _get_bias(mlp)
    weight_new = [_init_glorot(scale, w.shape, key) for w in weight_old]
    bias_new = [jnp.zeros(b.shape) for b in bias_old]

    mlp = eqx.tree_at(_get_bias, mlp, bias_new)
    mlp = eqx.tree_at(_get_weight, mlp, weight_new)
    return mlp


def plot_fit(df_obs, df_pred):
    """
  Plot the model prediction (df_pref) against the observed data (df_obs).
  The data to plot can typically be generated by the get_result_plot
  function.
  """
    cb_palette = ["#E69F00", "#56B4E9", "#009E73", "#F0E442", "#0072B2",
                  "#D55E00", "#CC79A7", "#999999"]
    p = (p9.ggplot(df_pred, p9.aes("time", "value", color="id")) +
         p9.geom_line(size=1.0) +
         p9.geom_point(data=df_obs, mapping=p9.aes("time", "value"), size=3.0) +
         p9.facet_wrap("~id") +
         p9.labs(x="Time", y="Measurement") +
         p9.scale_color_manual(values=cb_palette, name="Measurement id") +
         p9.theme_bw(base_size=18) +
         p9.theme(legend_position="bottom"))
    return p


# Flatten a tree to an array to allow gradient and Hessian functions to
# produce Array output
def flatten(v):
    def f(v):
        leaves, _ = jax.tree_util.tree_flatten(v)
        return jnp.concatenate([x.ravel() for x in leaves])

    out, pullback = jax.vjp(f, v)
    return out, lambda x: pullback(x)[0]


def build_MLP(in_size, out_size, width_size, hidden_layers, key, activation=jax.nn.tanh):
    mlp = eqx.nn.MLP(in_size=in_size,
                     out_size=out_size,
                     width_size=width_size,
                     depth=hidden_layers,
                     activation=activation,
                     key=key)
    return mlp
