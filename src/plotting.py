import jax.numpy as jnp
import pandas as pd
import plotnine as p9

from diffrax import SaveAt
from src.model_examples.lotka_volterra.setup_diffrax_model import get_result_plot as get_result_plot_lv
from src.model_examples.sir.setup_diffrax_model import get_result_plot as get_result_plot_sir
from src.ude_problem import UDEProblem
from typing import List

get_result_plot_funcs = {
    'lotka_volterra': get_result_plot_lv,
    'sir': get_result_plot_sir,
}


def plot_fit(
        df_obs: pd.DataFrame,
        df_pred: pd.DataFrame,
):
    """
  Plot the model prediction (df_pref) against the observed data (df_obs).
  The data to plot can typically be generated by the get_result_plot
  function.
  """
    cb_palette = ["#E69F00", "#56B4E9", "#009E73", "#F0E442", "#0072B2",
                  "#D55E00", "#CC79A7", "#999999"]
    p = (p9.ggplot(df_pred, p9.aes("time", "value", color="id")) +
         p9.geom_line(size=1.0) +
         p9.geom_point(data=df_obs, mapping=p9.aes("time", "value"), size=3.0) +
         p9.facet_wrap("~id") +
         p9.labs(x="Time", y="Measurement") +
         p9.scale_color_manual(values=cb_palette, name="Measurement id") +
         p9.theme_bw(base_size=18) +
         p9.theme(legend_position="bottom"))
    return p


def save_plot_results(
        trained_model: UDEProblem,
        u0: jnp.array,
        t_save: SaveAt,
        t_span: List,
        data: jnp.array,
        dataset: str,
        plot_name: str,
        plot_fmt: str,
        return_plot: bool = False,
):
    if trained_model.dynamical_model not in get_result_plot_funcs.keys():
        raise ValueError(f"Unknown dynamical model: {trained_model.dynamical_model}!")
    df_obs, df_pred = get_result_plot_funcs[trained_model.dynamical_model](
        trained_model,
        u0,
        t_save,
        t_span,
        data,
    )
    p = plot_fit(df_obs, df_pred)
    if return_plot:
        return p
    else:
        p.save(f"{dataset}_{plot_name}.{plot_fmt}")
